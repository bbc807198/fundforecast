@dataclass
class Config:
    """一次实验的全部配置。字段分组见注释。"""

    # ------------------------------------------------------------------
    # 一、路径与列名
    # ------------------------------------------------------------------
    csv_path: str = "daily_series.csv"   # 原始数据（相对 main.py 所在目录）
    out_dir: str = "outputs"             # 所有产物（预测 csv / 图 / 指标）都写到这里
    date_col: str = "report_date"        # 日期列名
    targets: Tuple[str, str] = ("purchase", "redeem")  # 申购、赎回（各建一个模型）

    # ------------------------------------------------------------------
    # 二、预测区间
    # ------------------------------------------------------------------
    forecast_start: str = "2014-09-01"
    forecast_end: str = "2014-09-30"

    # ------------------------------------------------------------------
    # 三、数据变换（水平/季节指数的构造）
    # ------------------------------------------------------------------
    # 分母水平：用"过去 level_ma 天（不含当天）的均值"作为当天所处的水平。
    # 这样 ratio = 当天值 / 近期水平，等于把"量级"剥掉，只留下周内形状和短期波动。
    # 为什么不直接让 LSTM 学原始值？因为 2013-07 到 2014-02 涨了 10 倍，
    # LSTM 无法外推出训练集之外的水平，直接用原始值几乎必然单调外推或走平。
    level_ma: int = 7
    ratio_clip: float = 3.0              # ratio 的截断上界，防止除零/异常值炸掉 loss

    # 目标归一化方式：
    #   "window_mean" —— 预测 ratio 相对"输入窗口内平均 ratio"的倍数（默认）
    #   "raw"         —— 直接预测 ratio
    # 为什么默认 window_mean：2013 年下半年数据一路上涨，ratio 的长期均值被抬到 1.1 左右；
    # 2014 年横盘后真实 ratio≈1.0，但模型会向训练集均值回归，造成系统性高估 10~15%
    # （回测里非常明显）。除以窗口均值后，目标变成"相对当下的形状"，长期漂移被消掉，
    # 预测时再乘回去即可。这是一个无泄漏的因果变换。
    target_norm: str = "window_mean"

    # ------------------------------------------------------------------
    # 四、样本窗口
    # ------------------------------------------------------------------
    lookback: int = 28        # 输入窗口长度（天）。28 = 4 周，能覆盖 4 个完整的周周期
    out_len: int = 31         # 预测长度：一次覆盖 31 天（最长月份），预测 9 月时截断到 30
    mode: str = "direct"      # "direct"（一次输出 H 天）或 "recursive"（单步 + 滚动 30 次）
    # 输出头结构：
    #   "future"    —— LSTM 只编码历史窗口，解码器逐天输入"那一天已知的日历特征 +
    #                  第几天/总天数"，输出当天的值。未来日历是已知信息，这是本数据
    #                  里最强的信号（周内效应、中秋），显式喂进去比让网络自己猜好得多。
    #                  参数量更少、小数据下更稳，默认用这个。
    #   "multistep" —— 经典做法：一次输出 out_len 个数。样本少时很难学准位置。
    head: str = "future"

    # ------------------------------------------------------------------
    # 五、水平（"基准线"）外推
    # ------------------------------------------------------------------
    # 实测结论（见 README）：这份数据的月度水平是"均值回复"的，1 个月尺度上
    # 做趋势外推会系统性高估（回测里趋势外推 WAPE≈31%，平坦水平 WAPE≈20%）。
    # 所以默认 level_mode="flat"：用指数加权平均（EWMA）估一个稳的当前水平，
    # 整个预测期水平保持不变；ratio 负责周内形状，节假日等由特征刻画。
    #
    # 如果你的品种确实有稳定趋势（例如持续增长的规模），改成 "trend"，
    # 它会用 log 空间加权最小二乘 + 阻尼外推（参数在下面）。
    level_mode: str = "flat"            # "flat" 或 "trend"
    level_ewma_halflife: float = 28.0   # flat 模式：EWMA 半衰期（天），越大越平滑
    level_window: int = 84              # trend 模式：用最近多少天拟合 log 趋势
    level_halflife: float = 28.0        # trend 模式：加权半衰期
    level_anchor: int = 7               # trend 模式：用最近多少天把拟合水平锚定到实际值
    damp: float = 0.90                  # trend 模式：趋势阻尼，<1 表示外推逐步收敛
    max_daily_slope: float = 0.01       # trend 模式：日斜率上限（log 空间），±1%/天
    max_total_drift: float = 0.15       # trend 模式：整段累计漂移上限（log 空间，≈±16%）

    # ------------------------------------------------------------------
    # 六、特征开关（想做消融实验就改这里）
    # ------------------------------------------------------------------
    use_both_targets: bool = True    # 申购模型是否也把赎回的 ratio 当输入（两者有共同的市场冲击）
    use_level_feature: bool = True   # 是否输入 log 水平（让模型知道当前处在什么量级）
    use_holiday_feature: bool = True # 是否输入节假日 / 调休标记

    # ------------------------------------------------------------------
    # 七、网络结构
    # ------------------------------------------------------------------
    hidden: int = 48          # LSTM 隐层维度，样本只有 ~380 条，32~64 足够，别上 128+
    layers: int = 1           # 层数，1 层通常最稳；2 层要配合更大 dropout
    dropout: float = 0.10     # 输出头/LSTM 层间 dropout

    # ------------------------------------------------------------------
    # 八、训练
    # ------------------------------------------------------------------
    epochs: int = 400         # 最大轮数（有早停，实际常常 100 轮左右就停）
    batch_size: int = 16
    lr: float = 5e-3
    weight_decay: float = 1e-4
    grad_clip: float = 1.0
    patience: int = 60        # 验证集连续多少轮不降就早停
    val_ratio: float = 0.20   # 时间序列末尾留多少比例做验证（不能随机切！）
    val_gap: int = 31         # 训练集与验证集之间空出的天数（防止窗口重叠导致信息泄漏）
    min_val: int = 15         # 验证集最少样本数
    loss: str = "huber"       # "mse" 或 "huber"（ratio 里单日异常值不少，huber 更稳，回测一致更好）
    input_noise: float = 0.0  # 训练时对输入加高斯噪声的强度（数据增强，0 表示关闭）
    sample_decay: float = 1.0 # 样本权重衰减：1.0 表示不加权；0.999 表示越近的样本越重要
    ensemble: int = 5         # 训练几个不同随机种子的模型做平均（降方差，通常能稳定提升）
    seed: int = 42
    device: str = "auto"      # "auto" / "cpu" / "cuda"

    # ------------------------------------------------------------------
    # 九、回测（walk-forward，按月滚动）
    # ------------------------------------------------------------------
    # 每次"用 M 月之前的数据训练，预测整个 M 月"，与 9 月的任务完全同构。
    backtest_start: str = "2014-04-01"   # 第一个被预测的月份（含）
    backtest_end: str = "2014-08-31"     # 最后一个被预测的月份（含）
    min_train_days: int = 240            # 训练天数少于这个值的月份直接跳过
    bootstrap: int = 2000                # 配对 bootstrap 次数，用来判断"变好"是否显著
    block: int = 7                       # bootstrap 分块长度（按周分块，保留周内相关性）

    # ------------------------------------------------------------------
    # 十、输出
    # ------------------------------------------------------------------
    save_models: bool = False
    plots: bool = True

    # ------------------------------------------------------------------
    # 便捷方法
    # ------------------------------------------------------------------
    def copy(self, **kwargs) -> "Config":
        """返回替换了若干字段的新配置，例如 cfg.copy(hidden=64, lr=1e-3)。"""
        unknown = set(kwargs) - set(self.__dataclass_fields__)
        if unknown:
            raise KeyError(f"未知配置项: {sorted(unknown)}")
        return replace(self, **kwargs)

    def to_dict(self) -> dict:
        d = asdict(self)
        d["targets"] = list(self.targets)
        return d


