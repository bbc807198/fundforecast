# ---------------------------------------------------------------------------
# 由 mode / head 推导出来的两个"长度"，避免各处重复判断，改结构时只改这里
# ---------------------------------------------------------------------------
def net_out_len(cfg: Config) -> int:
    """网络最后一个输出层的宽度（future 头的输出宽度由输入的未来协变量长度决定）。"""
    if cfg.mode == "recursive" or cfg.head == "future":
        return 1
    return cfg.out_len


def window_horizon(cfg: Config) -> int:
    """构造训练样本时，每个锚点要往后覆盖多少天。"""
    return 1 if cfg.mode == "recursive" else cfg.out_len


def future_head_active(cfg: Config) -> bool:
    """是否真的使用"未来协变量"解码头。recursive 模式每次只预测 1 天，用不上。"""
    return cfg.head == "future" and cfg.mode == "direct"
