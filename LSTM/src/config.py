"""
全局参数配置。

设计原则：
1) 所有"可能要调"的东西都放在这个 dataclass 里，命令行可以覆盖其中任意字段；
2) 训练脚本、回测脚本共用同一份配置，保证"预测"和"评估"用完全一样的流程，
   这样回测出来的分数才对线上的 9 月预测有参考价值；
3) 默认值是我在这份数据上试过后比较稳的一组，注释里写了每个参数的含义和经验范围。

调参时建议一次只改一个字段，然后跑 `python main.py --task backtest` 看回测指标变化。
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field, replace
from typing import List, Tuple


